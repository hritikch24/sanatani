/**
 * Image pipeline.
 *
 * Reads the full-size originals in assets/source/ and emits responsive AVIF +
 * WebP (plus one JPEG fallback) into public/, along with a generated module of
 * tiny inline blur placeholders.
 *
 * Run after adding or replacing any source image:
 *   npm run images
 *
 * Sources are kept in the repo so this is always reproducible; only the derived
 * files in public/ are served.
 */
import sharp from 'sharp';
import { mkdir, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const SRC = join(root, 'assets/source');
const OUT = join(root, 'public');

// The hero spans the viewport; banners are capped by the 760px article column.
const HERO_WIDTHS = [480, 768, 1100, 1365];
const BANNER_WIDTHS = [480, 760, 1120];

const JOBS = [
  { name: 'hero',    file: 'hero.png',    widths: HERO_WIDTHS,   jpeg: 1100, og: true },
  { name: 'gurukul', file: 'gurukul.png', widths: BANNER_WIDTHS, jpeg: 760,  og: true },
  { name: 'itihas',  file: 'itihas.png',  widths: BANNER_WIDTHS, jpeg: 760,  og: true },
  { name: 'mandir',  file: 'mandir.png',  widths: BANNER_WIDTHS, jpeg: 760,  og: true },
  { name: 'parv',    file: 'parv.png',    widths: BANNER_WIDTHS, jpeg: 760,  og: true },
  { name: 'brand',   file: 'brand.png',   widths: BANNER_WIDTHS, jpeg: 760,  og: false },
];

const kb = n => Math.round(n / 1024);

async function run() {
  await mkdir(OUT, { recursive: true });
  const placeholders = {};

  for (const job of JOBS) {
    const src = join(SRC, job.file);
    const meta = await sharp(src).metadata();
    const widths = job.widths.filter(w => w <= meta.width);
    if (!widths.includes(Math.min(meta.width, Math.max(...job.widths)))) {
      widths.push(Math.min(meta.width, Math.max(...job.widths)));
    }

    for (const w of widths) {
      const a = await sharp(src).resize({ width: w }).avif({ quality: 52, effort: 5 })
        .toFile(join(OUT, `${job.name}-${w}.avif`));
      const b = await sharp(src).resize({ width: w }).webp({ quality: 74, effort: 6 })
        .toFile(join(OUT, `${job.name}-${w}.webp`));
      console.log(`  ${job.name}-${w}  avif ${kb(a.size)}KB  webp ${kb(b.size)}KB`);
    }

    const j = await sharp(src).resize({ width: job.jpeg }).jpeg({ quality: 74, mozjpeg: true })
      .toFile(join(OUT, `${job.name}-${job.jpeg}.jpg`));
    console.log(`  ${job.name}-${job.jpeg}.jpg  ${kb(j.size)}KB (fallback)`);

    // 1200x630 social card, cropped from the centre of interest.
    if (job.og) {
      const o = await sharp(src)
        .resize({ width: 1200, height: 630, fit: 'cover', position: 'attention' })
        .jpeg({ quality: 80, mozjpeg: true })
        .toFile(join(OUT, `og-${job.name}.jpg`));
      console.log(`  og-${job.name}.jpg  ${kb(o.size)}KB`);
    }

    const lqip = await sharp(src).resize({ width: 20 }).blur(1).webp({ quality: 35 }).toBuffer();
    placeholders[job.name] = `data:image/webp;base64,${lqip.toString('base64')}`;
  }

  // The brand card is the sitewide social image.
  await sharp(join(SRC, 'brand.png'))
    .resize({ width: 1200, height: 630, fit: 'cover', position: 'centre' })
    .jpeg({ quality: 82, mozjpeg: true })
    .toFile(join(OUT, 'og-image.jpg'));
  console.log('  og-image.jpg (sitewide social card)');

  const banner = `// GENERATED by scripts/build-images.mjs — do not edit by hand.
// Tiny inline blur placeholders so a banner paints instantly while the real
// image downloads.
export const BLUR: Record<string, string> = ${JSON.stringify(placeholders, null, 2)};
`;
  await writeFile(join(root, 'app/components/blur.ts'), banner);
  console.log('\n  wrote app/components/blur.ts');
}

run().catch(e => { console.error(e); process.exit(1); });
